"""
BattLeDIM external benchmark evaluation.

Companion to batadal_benchmark.py, using a dataset built specifically for
LEAK detection (not cyber-attack detection like BATADAL), with real
customer-meter-shaped demand data instead of network valve/pump sensors.

DATASET: BattLeDIM 2018 (https://battledim.ucy.ac.cy)
  - 2018_SCADA.xlsx, sheet "Demands (L_h)": 82 monitored customer/junction
    demand nodes, 5-minute resolution, for the full year 2018.
  - 2018_Leakages.csv: continuous leak flow rate (m3/h) for 14 pipes,
    5-minute resolution, for the full year 2018. This is real, precise
    ground truth (independently generated by the dataset's creators).
  - 2018_Fixed_Leakages_Report.txt: official repair times, used only to
    cross-validate the episode end-times derived from 2018_Leakages.csv.

METHODOLOGY
  Unlike BATADAL (network-wide flow/pressure sensors), a pipe leak in this
  dataset does not uniformly affect every customer node -- it shows up as a
  large, sudden increase in ONE or a few nodes near that specific pipe.
  This script:
    1. Cross-validates leak episode start/end times against the official
       fixed-leakages report.
    2. For each leak episode, scans all 82 demand nodes with a TIGHT
       before/after window (3 days each side of the leak's start) to find
       the node(s) that actually show the leak -- a naive long-window
       comparison was tried first and found to be misleading (it picks up
       ordinary seasonal demand drift, not the leak itself; see
       docs/06_Validation.md for that finding).
    3. Only keeps a leak/node pairing as a usable test case if: (a) the
       matched node shows a genuinely large, isolated change (>15%), and
       (b) enough prior history exists within the 2018 dataset to build a
       valid baseline (>=84 days before the evaluation window).
    4. Checks, per case, whether the matched node's OWN baseline window is
       contaminated by a DIFFERENT leak affecting that same node -- the
       same diagnostic performed for BATADAL, now on a second real dataset.
    5. Adds negative-control cases: nodes that show no meaningful response
       to any leak in the full-network scan, tested at multiple points
       across the year.

WHAT THIS DOES AND DOES NOT TELL US
  This is real leak-detection data with real, independently-created ground
  truth -- unlike BATADAL, it is testing the actual problem this project is
  built for. It is still a simulated network (L-Town, EPANET-generated),
  not real customer billing meters, and only 82 of ~10,000 simulated
  consumers are individually monitored (the rest are aggregated). Treat
  this as a second, independent, and more directly relevant piece of
  evidence -- not a final production accuracy number.

USAGE
  Fully self-contained -- needs only the three raw files as downloaded from
  battledim.ucy.ac.cy, placed in the same folder as this script:
    2018_SCADA.xlsx
    2018_Leakages.csv
    2018_Fixed_Leakages_Report.txt   (optional, used only to print a
                                       cross-check against the official
                                       repair times -- not required to run)
    python battledim_benchmark.py
"""
import os
import sys
import pandas as pd
import numpy as np

DATA_DIR = os.path.dirname(os.path.abspath(__file__))

# Find src/leak_detection.py regardless of how many folders deep this script
# sits (e.g. repo_root/battledim_benchmark.py, or
# repo_root/notebooks/benchmarking/battledim_benchmark.py both work) --
# tries the script's own folder first, then walks up looking for a
# sibling "src" folder, rather than assuming one fixed depth.
_candidate_dirs = [DATA_DIR]
_walk = DATA_DIR
for _ in range(4):
    _walk = os.path.dirname(_walk)
    _candidate_dirs.append(os.path.join(_walk, "src"))

for _d in _candidate_dirs:
    if os.path.exists(os.path.join(_d, "leak_detection.py")):
        sys.path.insert(0, _d)
        break
else:
    print("ERROR: could not find leak_detection.py in any of these locations:")
    for _d in _candidate_dirs:
        print(f"  {_d}")
    print("Place leak_detection.py next to this script, or check your repo's src/ folder location.")
    sys.exit(1)

from leak_detection import analyze_leak_production_grade  # noqa: E402

RESULTS_CSV = os.path.join(DATA_DIR, "battledim_evaluation_results.csv")
TMP_CASE_CSV = os.path.join(DATA_DIR, "_battledim_case_tmp.csv")


def find_data_file(filename):
    """
    Searches likely locations for a data file, instead of assuming it sits
    right next to this script -- handles both a flat layout (everything in
    one folder) and the repo's data/benchmarking/ convention, regardless of
    how many folders deep this script itself is placed.
    """
    candidates = [DATA_DIR]
    walk = DATA_DIR
    for _ in range(4):
        walk = os.path.dirname(walk)
        candidates.append(os.path.join(walk, "data", "benchmarking"))
        candidates.append(walk)

    for d in candidates:
        p = os.path.join(d, filename)
        if os.path.exists(p):
            return p
    return None

MATCH_THRESHOLD_PCT = 15.0     # minimum tight-window % change to accept a node as "affected"
MIN_HISTORY_DAYS = 84          # ~12 weeks, matching the pipeline's own baseline+recent requirement
DATA_START = pd.Timestamp("2018-01-01 00:00:00")


def load_demands(scada_xlsx_path):
    """
    Loads the raw "Demands (L_h)" sheet (82 customer/junction nodes,
    5-minute resolution) and returns both:
      - the raw 5-minute data (needed for the tight-window node-matching
        step, which needs finer resolution than hourly to cleanly separate
        "before" from "after" a leak that starts mid-day)
      - an hourly-resampled version (mean L/h over each hour -> m3 for
        that hour), matching the hourly resolution analyze_leak_production_grade
        expects, the same way real customer meter exports are hourly.
    """
    demands_5min = pd.read_excel(scada_xlsx_path, sheet_name="Demands (L_h)")
    demands_5min["Timestamp"] = pd.to_datetime(demands_5min["Timestamp"])

    hourly = demands_5min.set_index("Timestamp").resample("h").mean() / 1000.0
    hourly = hourly.reset_index()

    return demands_5min, hourly


def cross_check_fixed_leaks_report(leak_ep, report_path):
    """Optional sanity check: compare our derived episode end-times against
    the dataset's own official repair-time report, if it's present."""
    if not os.path.exists(report_path):
        print("(No fixed-leaks report found -- skipping cross-check, not required to run.)")
        return

    reported = {}
    with open(report_path) as f:
        for line in f:
            line = line.strip()
            if not line.startswith("- "):
                continue
            parts = line[2:].split(",")
            if len(parts) != 2:
                continue
            pipe, end_time = parts[0].strip(), parts[1].strip()
            reported[pipe] = pd.Timestamp(end_time)

    print("Cross-checking derived leak end-times against the official report:")
    for _, ep in leak_ep.iterrows():
        if ep["pipe"] in reported:
            match = ep["end"] == reported[ep["pipe"]]
            print(f"  {ep['pipe']}: derived={ep['end']}  reported={reported[ep['pipe']]}  match={match}")


def load_leak_episodes(leakages_path):
    """Derive precise start/end/peak for each leak pipe from the continuous
    leak-flow-rate data (not just a binary flag)."""
    leaks = pd.read_csv(leakages_path, sep=";", decimal=",")
    leaks["Timestamp"] = pd.to_datetime(leaks["Timestamp"])
    leak_cols = [c for c in leaks.columns if c != "Timestamp"]

    episodes = []
    for col in leak_cols:
        vals = leaks[col].fillna(0).values
        active = vals > 0.001
        in_ep, start = False, None
        for i in range(len(active)):
            if active[i] and not in_ep:
                in_ep, start = True, i
            elif not active[i] and in_ep:
                in_ep = False
                episodes.append((col, leaks["Timestamp"].iloc[start], leaks["Timestamp"].iloc[i - 1]))
        if in_ep:
            episodes.append((col, leaks["Timestamp"].iloc[start], leaks["Timestamp"].iloc[-1]))

    return pd.DataFrame(episodes, columns=["pipe", "start", "end"])


def find_affected_node(demands_5min, node_cols, leak_start):
    """Tight before/after window scan: which node shows the leak?"""
    before = demands_5min[(demands_5min["Timestamp"] >= leak_start - pd.Timedelta(days=3)) &
                           (demands_5min["Timestamp"] < leak_start)]
    after = demands_5min[(demands_5min["Timestamp"] >= leak_start) &
                          (demands_5min["Timestamp"] < leak_start + pd.Timedelta(days=3))]
    if before.empty or after.empty:
        return None, None

    best_node, best_pct = None, -999
    for col in node_cols:
        b, a = before[col].mean(), after[col].mean()
        if b > 0.1:
            pct = (a - b) / b * 100
            if pct > best_pct:
                best_pct, best_node = pct, col
    return best_node, round(best_pct, 1)


def run_case(hourly_df, node, end_ts, ground_truth, dataset_label, case_name, results):
    formatted = hourly_df[hourly_df["Timestamp"] <= end_ts][["Timestamp", node]].dropna().copy()
    formatted.columns = ["Hourly", "Consumption m3"]
    formatted.to_csv(TMP_CASE_CSV, index=False)

    res = analyze_leak_production_grade(TMP_CASE_CSV, "Commercial")
    results.append({
        "dataset": dataset_label, "case": case_name, "node": node, "end_ts": end_ts,
        "ground_truth_leak": ground_truth, "predicted": res["Leak_Suspected"],
        "status": res["Status"], "priority_score": res.get("Priority_Score"),
        "details": (res.get("Details") or "")[:200],
    })


def main():
    leakages_path = find_data_file("2018_Leakages.csv")
    scada_path = find_data_file("2018_SCADA.xlsx")
    report_path = find_data_file("2018_Fixed_Leakages_Report.txt")  # optional
    if not leakages_path or not scada_path:
        print("ERROR: could not find 2018_Leakages.csv / 2018_SCADA.xlsx.")
        print("Checked the script's own folder and data/benchmarking/ up to 4 levels up.")
        print("Place both files in data/benchmarking/, or next to this script.")
        sys.exit(1)
    print(f"Using 2018_Leakages.csv at: {leakages_path}")
    print(f"Using 2018_SCADA.xlsx at: {scada_path}")

    print("Loading leak episodes from 2018_Leakages.csv...")
    leak_ep = load_leak_episodes(leakages_path)
    if report_path:
        cross_check_fixed_leaks_report(leak_ep, report_path)
    else:
        print("(2018_Fixed_Leakages_Report.txt not found -- skipping cross-check, not required to run.)")

    print("\nLoading and resampling demand data from 2018_SCADA.xlsx (this can take a minute)...")
    demands_5min, hourly_df = load_demands(scada_path)
    node_cols = [c for c in hourly_df.columns if c != "Timestamp"]

    results = []
    print("\nMatching leak episodes to affected demand nodes...")

    used_nodes_by_time = []  # track (node, start, end) to check cross-leak contamination
    for _, ep in leak_ep.iterrows():
        node, pct = find_affected_node(demands_5min, node_cols, ep["start"])
        if node is None:
            continue
        end_ts = ep["start"] + pd.Timedelta(days=3)
        history_days = (end_ts - pd.Timedelta(weeks=4) - DATA_START).days

        usable = pct is not None and pct > MATCH_THRESHOLD_PCT and history_days >= MIN_HISTORY_DAYS
        print(f"  {ep['pipe']}: node={node}, pct_change={pct}, history_days={history_days}, usable={usable}")

        if usable:
            run_case(hourly_df, node, end_ts, True, "battledim_positive", f"{ep['pipe']}_on_{node}", results)
            used_nodes_by_time.append((ep["pipe"], node, ep["start"], ep["end"]))

    # --- Negative controls: consistently-quiet nodes at several points across the year ---
    quiet_nodes = ["n357", "n387", "n369", "n41", "n42"]
    check_points = pd.date_range("2018-03-01", "2018-11-01", periods=5)
    for node in quiet_nodes:
        for i, end_ts in enumerate(check_points):
            history_days = (end_ts - pd.Timedelta(weeks=4) - DATA_START).days
            if history_days < MIN_HISTORY_DAYS:
                continue
            run_case(hourly_df, node, end_ts, False, "battledim_negative", f"{node}_point_{i+1}", results)

    df = pd.DataFrame(results)
    df.to_csv(RESULTS_CSV, index=False)
    if os.path.exists(TMP_CASE_CSV):
        os.remove(TMP_CASE_CSV)

    df["predicted_bool"] = df["predicted"] == "YES"
    tp = int(((df["ground_truth_leak"]) & (df["predicted_bool"])).sum())
    fn = int(((df["ground_truth_leak"]) & (~df["predicted_bool"])).sum())
    fp = int(((~df["ground_truth_leak"]) & (df["predicted_bool"])).sum())
    tn = int(((~df["ground_truth_leak"]) & (~df["predicted_bool"])).sum())

    precision = tp / (tp + fp) if (tp + fp) > 0 else float("nan")
    recall = tp / (tp + fn) if (tp + fn) > 0 else float("nan")
    f1 = (2 * precision * recall / (precision + recall)) if (precision + recall) > 0 else float("nan")
    fpr = fp / (fp + tn) if (fp + tn) > 0 else float("nan")

    print()
    print(df[["dataset", "case", "ground_truth_leak", "predicted", "status", "priority_score"]].to_string(index=False))
    print()
    print("=" * 60)
    print("CONFUSION MATRIX")
    print("=" * 60)
    print(f"  True Positives  (real leak, flagged YES):  {tp}")
    print(f"  False Negatives (real leak, flagged NO):   {fn}")
    print(f"  False Positives (clean, flagged YES):      {fp}")
    print(f"  True Negatives  (clean, flagged NO):       {tn}")
    print()
    print(f"  Precision: {precision:.3f}" if precision == precision else "  Precision: n/a")
    print(f"  Recall:    {recall:.3f}" if recall == recall else "  Recall: n/a")
    print(f"  F1:        {f1:.3f}" if f1 == f1 else "  F1: n/a")
    print(f"  FPR:       {fpr:.3f}" if fpr == fpr else "  FPR: n/a")
    print("=" * 60)
    print(f"\nFull results saved to: {RESULTS_CSV}")


if __name__ == "__main__":
    main()