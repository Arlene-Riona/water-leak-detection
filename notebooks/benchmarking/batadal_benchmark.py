"""
BATADAL external benchmark evaluation.

Measures the current leak detection logic (analyze_leak_production_grade)
against a real, independently-labeled external dataset -- not synthetic
data generated by this project. This supersedes the earlier benchmark
notebook, which (a) tested an outdated, abandoned version of the detection
logic, and (b) only ran a single anecdotal check on one file, rather than
computing real precision/recall/F1.

DATASETS
  dataset03.csv -- 1 full year (Jan 2014-Jan 2015), ZERO labeled attacks.
                   Used as a pure false-positive control on real data.
  dataset04.csv -- ~6 months (Jul-Dec 2016), 7 distinct labeled attack
                   episodes (24-110 hrs each). Used for both true-positive
                   test cases (near each episode) and true-negative test
                   cases (clean gaps between episodes).

Both are from the BATADAL water-network SCADA challenge. Ground truth
(ATT_FLAG) was assigned independently by the dataset's creators, not by
this project -- this is real external validation, not self-generated
synthetic testing.

METHODOLOGY
  The detection function evaluates one fixed "last 4 weeks vs prior 8 weeks"
  window per file call. To get multiple real test cases instead of a single
  anecdotal check, this script truncates each dataset at many different end
  points and treats each truncation as its own independent test case:
    - dataset04: one case anchored just after each of the 7 attack episodes
      (so the episode falls inside that truncation's own "recent 4 weeks"
      window), plus several cases anchored in clean gaps between episodes.
    - dataset03: several cases spread across the clean year.
  Ground truth for each case is computed the exact same way the pipeline
  itself defines its evaluation window (max_date - 4 weeks to max_date),
  not by an external heuristic.

MAPPING
  F_V2 (a valve flow sensor) -> Consumption m3
  DATETIME                   -> Hourly
  Category: "Industrial" (matches the closest category thresholds to a
  network-scale flow sensor; there is no BATADAL-native customer category).

WHAT THIS DOES AND DOES NOT TELL US
  BATADAL is a cyber-physical ATTACK detection dataset (SCADA pump/valve/
  tank sensors across a distribution network), not customer billing meters.
  A result here is evidence about whether the underlying anomaly-detection
  MATH generalizes to a different real-world signal -- it is not proof the
  system catches real customer leaks. Treat accordingly; see
  docs/06_Validation.md for the full caveat.

USAGE
  Place dataset03.csv and dataset04.csv in the same folder as this script
  (or edit DATA_DIR below), then run:
    python batadal_benchmark.py
"""
import os
import sys
import pandas as pd
import numpy as np

# --- CONFIG ---
DATA_DIR = os.path.dirname(os.path.abspath(__file__))

# Find src/leak_detection.py regardless of how many folders deep this script
# sits (e.g. repo_root/batadal_benchmark.py, or
# repo_root/notebooks/benchmarking/batadal_benchmark.py both work) --
# tries the script's own folder first, then walks up looking for a
# sibling "src" folder, rather than assuming one fixed depth.
_candidate_dirs = [DATA_DIR]
_walk = DATA_DIR
for _ in range(4):
    _walk = os.path.dirname(_walk)
    _candidate_dirs.append(os.path.join(_walk, "src"))

for _d in _candidate_dirs:
    if os.path.exists(os.path.join(_d, "leak_detection.py")):
        sys.path.insert(0, _d)
        break
else:
    print("ERROR: could not find leak_detection.py in any of these locations:")
    for _d in _candidate_dirs:
        print(f"  {_d}")
    print("Place leak_detection.py next to this script, or check your repo's src/ folder location.")
    sys.exit(1)

from leak_detection import analyze_leak_production_grade  # noqa: E402

RESULTS_CSV = os.path.join(DATA_DIR, "batadal_evaluation_results.csv")
TMP_CASE_CSV = os.path.join(DATA_DIR, "_batadal_case_tmp.csv")


def find_data_file(filename):
    """
    Searches likely locations for a data file, instead of assuming it sits
    right next to this script -- handles both a flat layout (everything in
    one folder) and the repo's data/benchmarking/ convention, regardless of
    how many folders deep this script itself is placed.
    """
    candidates = [DATA_DIR]
    walk = DATA_DIR
    for _ in range(4):
        walk = os.path.dirname(walk)
        candidates.append(os.path.join(walk, "data", "benchmarking"))
        candidates.append(walk)

    for d in candidates:
        p = os.path.join(d, filename)
        if os.path.exists(p):
            return p
    return None


def load_batadal(path):
    """Load a raw BATADAL CSV and parse its DATETIME column."""
    raw = pd.read_csv(path)
    raw.columns = raw.columns.str.strip()
    raw["DATETIME_parsed"] = pd.to_datetime(raw["DATETIME"], dayfirst=True, errors="coerce")
    raw = raw.dropna(subset=["DATETIME_parsed"]).sort_values("DATETIME_parsed").reset_index(drop=True)
    return raw


def make_truncated_case(raw, end_ts, tmp_path):
    """
    Truncate raw BATADAL data to end_ts, reformat as (Hourly, Consumption m3),
    and compute ground truth using the SAME window definition the pipeline
    itself uses (max_date - 4 weeks to max_date) -- not an external heuristic.
    """
    trunc = raw[raw["DATETIME_parsed"] <= end_ts].copy()
    formatted = pd.DataFrame({
        "Hourly": trunc["DATETIME_parsed"],
        "Consumption m3": pd.to_numeric(trunc["F_V2"], errors="coerce"),
    }).dropna().reset_index(drop=True)
    formatted.to_csv(tmp_path, index=False)

    max_date = formatted["Hourly"].max()
    four_weeks_ago = max_date - pd.Timedelta(weeks=4)
    window = trunc[(trunc["DATETIME_parsed"] >= four_weeks_ago) & (trunc["DATETIME_parsed"] <= end_ts)]
    ground_truth = bool((window["ATT_FLAG"] == 1).any()) if "ATT_FLAG" in trunc.columns else False
    baseline_days = (four_weeks_ago - trunc["DATETIME_parsed"].min()).days
    return ground_truth, baseline_days


def run_case(raw, end_ts, dataset_name, case_name, results):
    ground_truth, baseline_days = make_truncated_case(raw, end_ts, TMP_CASE_CSV)
    res = analyze_leak_production_grade(TMP_CASE_CSV, "Industrial")
    results.append({
        "dataset": dataset_name,
        "case": case_name,
        "end_ts": end_ts,
        "ground_truth_attack": ground_truth,
        "baseline_days_available": baseline_days,
        "predicted": res["Leak_Suspected"],
        "status": res["Status"],
        "priority_score": res.get("Priority_Score"),
        "details": (res.get("Details") or "")[:200],
    })


def main():
    d03_path = find_data_file("dataset03.csv")
    d04_path = find_data_file("dataset04.csv")
    if not d03_path or not d04_path:
        print("ERROR: could not find dataset03.csv / dataset04.csv.")
        print("Checked the script's own folder and data/benchmarking/ up to 4 levels up.")
        print("Place both files in data/benchmarking/, or next to this script.")
        sys.exit(1)
    print(f"Using dataset03.csv at: {d03_path}")
    print(f"Using dataset04.csv at: {d04_path}")

    d03 = load_batadal(d03_path)
    d04 = load_batadal(d04_path)
    results = []

    # --- dataset04: one case per attack episode, truncated 3 days after episode end ---
    episode_ends = [
        pd.Timestamp("2016-09-16 00:00:00"),
        pd.Timestamp("2016-09-27 10:00:00"),
        pd.Timestamp("2016-10-11 20:00:00"),
        pd.Timestamp("2016-11-02 16:00:00"),
        pd.Timestamp("2016-11-29 04:00:00"),
        pd.Timestamp("2016-12-10 04:00:00"),
        pd.Timestamp("2016-12-19 04:00:00"),
    ]
    max_d04 = d04["DATETIME_parsed"].max()
    for i, ep_end in enumerate(episode_ends):
        end_ts = min(ep_end + pd.Timedelta(days=3), max_d04)
        run_case(d04, end_ts, "dataset04", f"episode_{i + 1}_end+3d", results)

    # --- dataset04: additional truncation points spread between episodes ---
    # NOTE: these are NOT guaranteed to be clean -- some fall close enough to an
    # earlier episode that it lands inside their own 4-week evaluation window.
    # Ground truth is still computed correctly (from real ATT_FLAG data, using
    # the pipeline's own window definition) regardless of what these points
    # were originally intended to sample -- this just means some of these
    # ended up as additional true-positive/false-negative test cases rather
    # than the true-negative cases they were meant to be.
    interim_points = [
        pd.Timestamp("2016-09-08 00:00:00"),
        pd.Timestamp("2016-10-04 00:00:00"),
        pd.Timestamp("2016-11-19 00:00:00"),
    ]
    for i, end_ts in enumerate(interim_points):
        run_case(d04, end_ts, "dataset04", f"interim_point_{i + 1}", results)

    # --- dataset03: fully clean year, spread truncation points ---
    clean_points_d03 = pd.date_range("2014-05-01", "2014-12-25", periods=8)
    for i, end_ts in enumerate(clean_points_d03):
        run_case(d03, end_ts, "dataset03", f"clean_point_{i + 1}", results)

    df = pd.DataFrame(results)
    df.to_csv(RESULTS_CSV, index=False)
    if os.path.exists(TMP_CASE_CSV):
        os.remove(TMP_CASE_CSV)

    # --- Confusion matrix + metrics ---
    df["predicted_bool"] = df["predicted"] == "YES"
    tp = int(((df["ground_truth_attack"]) & (df["predicted_bool"])).sum())
    fn = int(((df["ground_truth_attack"]) & (~df["predicted_bool"])).sum())
    fp = int(((~df["ground_truth_attack"]) & (df["predicted_bool"])).sum())
    tn = int(((~df["ground_truth_attack"]) & (~df["predicted_bool"])).sum())

    precision = tp / (tp + fp) if (tp + fp) > 0 else float("nan")
    recall = tp / (tp + fn) if (tp + fn) > 0 else float("nan")
    f1 = (2 * precision * recall / (precision + recall)) if (precision + recall) > 0 else float("nan")
    fpr = fp / (fp + tn) if (fp + tn) > 0 else float("nan")

    print(df[["dataset", "case", "ground_truth_attack", "baseline_days_available",
               "predicted", "status", "priority_score"]].to_string(index=False))
    print()
    print("=" * 60)
    print("CONFUSION MATRIX")
    print("=" * 60)
    print(f"  True Positives  (real attack, flagged YES):  {tp}")
    print(f"  False Negatives (real attack, flagged NO):   {fn}")
    print(f"  False Positives (clean, flagged YES):        {fp}")
    print(f"  True Negatives  (clean, flagged NO):         {tn}")
    print()
    print(f"  Precision: {precision:.3f}" if precision == precision else "  Precision: n/a (no positive predictions)")
    print(f"  Recall:    {recall:.3f}" if recall == recall else "  Recall: n/a")
    print(f"  F1:        {f1:.3f}" if f1 == f1 else "  F1: n/a")
    print(f"  FPR:       {fpr:.3f}" if fpr == fpr else "  FPR: n/a")
    print("=" * 60)
    print(f"\nFull per-case results saved to: {RESULTS_CSV}")


if __name__ == "__main__":
    main()